/**
 * Ensures verified official radar listings exist in MongoDB.
 * If count is less than 15, inserts or refreshes them with dynamic future deadlines.
 */
export const ensureDefaultOfficialRadarOpportunities = async ({ force = false } = {}) => {
  try {
    console.log(`[SeedOfficialRadar] ⚡ Syncing/refreshing ${VERIFIED_RADAR_OPPORTUNITIES.length} verified official radar listings...`)

    let seededCount = 0
    for (const opp of VERIFIED_RADAR_OPPORTUNITIES) {
      const query = {
        title: opp.title,
        'company.name': opp.company.name,
        'source.type': 'official_radar',
      }

      const updateDoc = {
        ...opp,
        deadline: getFutureDate(120),
        status: 'open',
        isPublished: true,
      }

      await Opportunity.findOneAndUpdate(query, updateDoc, { upsert: true, new: true, setDefaultsOnInsert: true })
      seededCount++
    }

    const totalNow = await Opportunity.countDocuments({ 'source.type': 'official_radar' })
    console.log(`[SeedOfficialRadar] 🎉 Successfully seeded/refreshed official radar opportunities. Total active: ${totalNow}`)
    return { seeded: seededCount, total: totalNow }
  } catch (error) {
    console.error('[SeedOfficialRadar] ❌ Error seeding official radar opportunities:', error.message)
    return { error: error.message }
  }
}
