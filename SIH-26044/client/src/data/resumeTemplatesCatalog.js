/**
 * Returns a template by its ID, or the reference template as fallback.
 */
export const getTemplateById = (templateId) => {
  if (!templateId) return REFERENCE_TEMPLATE
  return RESUME_TEMPLATES.find((t) => t.id === templateId) || REFERENCE_TEMPLATE
}

/**
 * Filter templates by query, category, layout, atsSafe flag.
 */
export const filterTemplates = ({
  search = '',
  category = 'all',
  layout = 'all',
  atsSafeOnly = false,
  density = 'all',
}) => {
  const query = search.toLowerCase().trim()
  return RESUME_TEMPLATES.filter((tpl) => {
    // Search filter
    if (query) {
      const matchName = tpl.name.toLowerCase().includes(query)
      const matchDesc = tpl.description.toLowerCase().includes(query)
      const matchId = tpl.id.toLowerCase().includes(query)
      const matchCat = tpl.categories.some((c) => c.toLowerCase().includes(query))
      if (!matchName && !matchDesc && !matchId && !matchCat) return false
    }

    // Category filter
    if (category !== 'all') {
      if (!tpl.categories.includes(category)) return false
    }

    // Layout filter
    if (layout !== 'all') {
      if (tpl.layout !== layout) return false
    }

    // ATS Safe filter
    if (atsSafeOnly) {
      if (tpl.atsClass !== 'ats-safe' && !tpl.atsParseable) return false
    }

    // Density filter
    if (density !== 'all') {
      if (tpl.density !== density) return false
    }

    return true
  })
}

